"use strict";
/* ============================================================================
   EduSphere mobile — (re)generate a platform project and re-apply our sources
   ----------------------------------------------------------------------------
   The Android Gradle project is committed and builds from a clone. The Xcode
   project cannot be (it is a binary-ish .pbxproj that only Xcode's generator
   should write), so this script is the reproducible answer the roadmap asks
   for:

       npm run add:android     → npx cap add android   (+ restores our files)
       npm run add:ios         → npx cap add ios       (+ restores our files)

   Both are idempotent:
     • if the platform project already exists, only `cap sync` runs;
     • if it is missing, the committed EduSphere sources are snapshotted, the
       canonical project is generated by Capacitor, and our files are written
       back over it — so the manifest permissions, the deep-link intent filter,
       the KeyStore/Keychain plugin, Info.plist privacy strings and the Podfile
       are never lost.

   Nothing here needs a network connection beyond the npm install that
   produced mobile/node_modules.
   ========================================================================== */
const { execFileSync } = require("child_process");
const fs = require("fs");
const path = require("path");

const MOBILE = path.resolve(__dirname, "..");
const ANDROID = path.join(MOBILE, "android");
const IOS = path.join(MOBILE, "ios");

/** Files EduSphere owns; they survive a `cap add` regeneration. */
const ANDROID_MANAGED = [
  "app/src/main/AndroidManifest.xml",
  "app/src/main/java/app/edusphere/mobile/MainActivity.java",
  "app/src/main/java/app/edusphere/mobile/EduSphereNativePlugin.java",
  "app/src/main/java/app/edusphere/mobile/SecureTokenStore.java",
  "app/src/main/java/app/edusphere/mobile/SqliteStore.java",
  "app/src/main/res/xml/network_security_config.xml",
  "app/src/main/res/values/strings.xml",
  "app/src/main/res/values/styles.xml",
  "app/src/main/res/values/colors.xml",
  "app/src/main/res/drawable/splash.xml",
  "app/build.gradle",
  "app/proguard-rules.pro",
  "capacitor.settings.gradle",
  "variables.gradle",
  "gradle.properties",
];

const IOS_MANAGED = [
  "App/App/Info.plist",
  "App/App/AppDelegate.swift",
  "App/App/EduSphereNativePlugin.swift",
  "App/App/SecureTokenStore.swift",
  "App/App/SqliteStore.swift",
  "App/Podfile",
];

function exists(target) {
  try {
    return fs.existsSync(target);
  } catch (e) {
    return false;
  }
}

function snapshot(root, files, patterns) {
  const backup = {};
  for (const relative of files) {
    const absolute = path.join(root, relative);
    if (exists(absolute)) backup[relative] = fs.readFileSync(absolute);
  }
  for (const pattern of patterns || []) {
    const dir = path.join(root, pattern.dir);
    if (!exists(dir)) continue;
    for (const name of fs.readdirSync(dir)) {
      if (!pattern.match.test(name)) continue;
      const relative = path.join(pattern.dir, name);
      backup[relative] = fs.readFileSync(path.join(root, relative));
    }
  }
  return backup;
}

function restore(root, backup) {
  let restored = 0;
  for (const [relative, contents] of Object.entries(backup)) {
    const absolute = path.join(root, relative);
    fs.mkdirSync(path.dirname(absolute), { recursive: true });
    fs.writeFileSync(absolute, contents);
    restored += 1;
  }
  return restored;
}

function hasCapCli() {
  return exists(path.join(MOBILE, "node_modules", "@capacitor", "cli"));
}

function run(command, args, cwd) {
  execFileSync(command, args, { cwd: cwd || MOBILE, stdio: "inherit" });
}

function platformExists(platform) {
  if (platform === "android") return exists(path.join(ANDROID, "app", "build.gradle"));
  return exists(path.join(IOS, "App", "App.xcodeproj", "project.pbxproj"));
}

function ensure(platform) {
  if (!hasCapCli()) {
    throw new Error("mobile/node_modules is missing — run `npm install` inside mobile/ first");
  }
  if (platform === "ios" && process.platform !== "darwin") {
    // Generating the project works anywhere; BUILDING it needs macOS + Xcode.
    console.log("note: the iOS project is generated here, but only macOS with Xcode can build it.");
  }

  if (platformExists(platform)) {
    console.log(platform + " project already present — syncing only.");
    run("npx", ["cap", "sync", platform]);
    return { created: false };
  }

  const root = platform === "android" ? ANDROID : IOS;
  const managed = platform === "android" ? ANDROID_MANAGED : IOS_MANAGED;
  const backup = snapshot(root, managed, platform === "android"
    ? [{ dir: "app/src/main/res/mipmap-xxxhdpi", match: /\.png$/ }]
    : []);

  /* `cap add` refuses to run into a non-empty folder, so the committed sources
     are set aside (they are in memory AND on disk in git) and put back after. */
  const stash = path.join(MOBILE, ".platform-stash", platform);
  fs.rmSync(stash, { recursive: true, force: true });
  if (exists(root)) fs.renameSync(root, stash);
  try {
    run("npx", ["cap", "add", platform]);
  } finally {
    fs.mkdirSync(root, { recursive: true });
    restore(root, backup);
    fs.rmSync(stash, { recursive: true, force: true });
  }
  run("npx", ["cap", "sync", platform]);
  console.log(platform + " project generated and EduSphere sources restored.");
  return { created: true };
}

function main(argv) {
  const platform = (argv[0] || "").toLowerCase();
  if (platform !== "android" && platform !== "ios") {
    console.error("usage: node scripts/add-platforms.js <android|ios>");
    process.exit(2);
  }
  ensure(platform);
}

if (require.main === module) {
  try {
    main(process.argv.slice(2));
  } catch (error) {
    console.error("Could not prepare the " + (process.argv[2] || "") + " project: " + (error && error.message ? error.message : error));
    process.exit(1);
  }
}

module.exports = { ensure, snapshot, restore, platformExists, ANDROID_MANAGED, IOS_MANAGED };
